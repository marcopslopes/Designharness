#!/usr/bin/env node
/**
 * Writes context/design-system/COMPONENTS-INDEX.md: every component exported
 * from context/design-system/ds, one line each, with its own props, read
 * from the TypeScript types. `--check` fails when the file is out of date.
 *
 *   node scripts/ds-index.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

const repo = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const dsDir = path.join(repo, 'context/design-system/ds')
const out = path.join(repo, 'context/design-system/COMPONENTS-INDEX.md')
const entry = path.join(dsDir, 'index.ts')

const program = ts.createProgram([entry], {
  jsx: ts.JsxEmit.ReactJSX,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  target: ts.ScriptTarget.ES2022,
  strict: true,
  skipLibCheck: true,
  noEmit: true,
})
const checker = program.getTypeChecker()
const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(entry))

const own = (decl) => decl.getSourceFile().fileName.startsWith(dsDir)
const literalUnion = (type) => {
  const values = (type.isUnion() ? type.types : [type]).filter((t) => !(t.flags & ts.TypeFlags.Undefined))
  if (values.length < 2 || !values.every((t) => t.isLiteral() || t.flags & ts.TypeFlags.BooleanLiteral)) return null
  if (values.every((t) => t.flags & ts.TypeFlags.BooleanLiteral)) return null
  return values
    .map((t) => checker.typeToString(t, undefined, ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType))
    .join(' | ')
}
const typeText = (type) =>
  literalUnion(type) ??
  checker
    .typeToString(
      type,
      undefined,
      ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType,
    )
    .replace(/\s*\|\s*undefined\b/g, '')
    .replace(/\bReact\./g, '')
const clip = (s, n = 90) => (s.length > n ? `${s.slice(0, n - 1)}…` : s)

const byFile = new Map()
for (const exported of checker.getExportsOfModule(moduleSymbol)) {
  const name = exported.getName()
  if (!/^[A-Z]/.test(name)) continue
  const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported
  const decl = symbol.valueDeclaration
  if (!decl || !own(decl)) continue
  const [signature] = checker.getTypeOfSymbolAtLocation(symbol, decl).getCallSignatures()
  if (!signature) continue

  const [param] = signature.getParameters()
  const props = []
  let inherits = ''
  if (param) {
    const propsType = checker.getTypeOfSymbolAtLocation(param, decl)
    for (const prop of checker.getPropertiesOfType(propsType)) {
      const pDecl = prop.valueDeclaration ?? prop.declarations?.[0]
      if (!pDecl) continue
      if (!own(pDecl)) {
        const host = checker.typeToString(propsType).match(/(\w+)HTMLAttributes<HTML(\w+?)Element>/)
        inherits ||= host ? `<${host[2].toLowerCase()}> attrs` : 'HTML attrs'
        continue
      }
      if (prop.getName() === 'className') continue
      const optional = prop.flags & ts.SymbolFlags.Optional ? '?' : ''
      props.push(`${prop.getName()}${optional}: ${clip(typeText(checker.getTypeOfSymbolAtLocation(prop, pDecl)))}`)
    }
  }
  const file = path.relative(dsDir, decl.getSourceFile().fileName)
  const line = `- \`${name}\`${props.length ? ` ${props.join(' · ')}` : ''}${inherits ? ` (+ ${inherits})` : ''}`
  if (!byFile.has(file)) byFile.set(file, [])
  byFile.get(file).push(line)
}

const body = [
  '# Components — generated index',
  '',
  'Generated by `npm run ds:index` from the types in `context/design-system/ds`. Do not edit by hand.',
  'One line per exported component: its own props (`?` = optional), then any inherited HTML attributes.',
  'Open a component file only when a prop here is unclear.',
  '',
  ...[...byFile.keys()].sort().flatMap((file) => [`## ${file}`, '', ...byFile.get(file), '']),
].join('\n')

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
    console.error('context/design-system/COMPONENTS-INDEX.md is out of date. Run: npm run ds:index')
    process.exit(1)
  }
} else {
  writeFileSync(out, body)
  console.log(`Wrote ${path.relative(repo, out)} (${[...byFile.values()].flat().length} components)`)
}
