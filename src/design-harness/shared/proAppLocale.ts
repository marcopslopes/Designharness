export function localizedBusinessSettingsSections(
  lang: ProAppLang,
  sections: ProAppSettingsSection[],
): ProAppSettingsSection[] {
  if (lang === 'en') return sections
  return sections.map((section) => {
    const labelKey = SETTINGS_LABEL_MAP[section.label]
    return {
      label: labelKey ? CATALOGS.es[labelKey] : section.label,
      rows: section.rows.map((row) => ({
        ...row,
        title: SETTINGS_ROW_MAP[row.title] ?? row.title,
      })),
    }
  })
}

export type LocaleValue = {
  lang: ProAppLang
  t: (key: MsgKey) => string
}

export const ProAppLocaleContext = createContext<LocaleValue>({
  lang: 'en',
  t: (key) => EN[key],
})

export function useProAppLocale(): LocaleValue {
  return useContext(ProAppLocaleContext)
}
