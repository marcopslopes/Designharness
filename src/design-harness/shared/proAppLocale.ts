export type ProAppLang = 'en' | 'es'

export function parseProAppLang(value: string | null | undefined): ProAppLang {
  const v = (value ?? '').trim().toLowerCase()
  if (v === 'es' || v.startsWith('es-')) return 'es'
  return 'en'
}

