#!/usr/bin/env node
/**
 * Skill usage tracker hook
 * 
 * Tracks which skills are used and how often. Logs to:
 * - harness/logs/skill-usage.jsonl (append-only log)
 * - harness/logs/skill-usage-summary.md (human-readable summary)
 * 
 * Triggered by: any tool call that loads a skill
 * Hook type: postToolUse (after tool completes)
 */

import { readFileSync, appendFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = join(__dirname, '../..');

// Paths
const USAGE_LOG = join(REPO_ROOT, 'harness/logs/skill-usage.jsonl');
const USAGE_SUMMARY = join(REPO_ROOT, 'harness/logs/skill-usage-summary.md');

// Ensure logs directory exists
const logsDir = dirname(USAGE_LOG);
if (!existsSync(logsDir)) {
  mkdirSync(logsDir, { recursive: true });
}

/** A skill counts only when the tool's path is that skill's SKILL.md, not when the file contents mention one. */
function skillFromPayload(raw) {
  let data
  try {
    data = JSON.parse(raw)
  } catch {
    return null
  }
  const input = data.tool_input || data.toolInput || {}
  const filePath = [input.file_path, input.path, input.target_file, input.filePath]
    .filter((value) => typeof value === 'string')
    .join('\n')
  const match = filePath.match(/harness\/(?:skills\/([^/\\]+)|(harness-audit))\/SKILL\.md/)
  return match ? match[1] || match[2] : null
}

function readStdin() {
  return new Promise((resolve) => {
    const chunks = []
    process.stdin.on('data', (chunk) => chunks.push(chunk))
    process.stdin.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')))
    process.stdin.on('error', () => resolve(''))
  })
}

/**
 * Get current designer from profile
 */
function getDesignerName() {
  const profilePath = join(REPO_ROOT, 'designer-profile.local.md');
  
  if (!existsSync(profilePath)) {
    return 'unknown';
  }
  
  try {
    const profile = readFileSync(profilePath, 'utf-8');
    const nameMatch = profile.match(/^-\s*Name:\s*(.+)$/m);
    return nameMatch ? nameMatch[1].trim() : 'unknown';
  } catch (err) {
    return 'unknown';
  }
}

/**
 * Log skill usage event
 */
function sessionOf(data) {
  return data.session_id || data.conversation_id || process.env.CURSOR_SESSION_ID || process.env.CLAUDE_SESSION_ID || 'unknown'
}

function logUsage(skillName, data) {
  const event = {
    timestamp: new Date().toISOString(),
    skill: skillName,
    designer: getDesignerName(),
    session: sessionOf(data),
    cwd: data.cwd || process.cwd()
  };
  
  // Append to JSONL log
  appendFileSync(USAGE_LOG, JSON.stringify(event) + '\n');
  
  // Update summary
  updateSummary();
}

/**
 * Generate usage summary from log
 */
function updateSummary() {
  if (!existsSync(USAGE_LOG)) return;
  
  const lines = readFileSync(USAGE_LOG, 'utf-8').trim().split('\n');
  const events = lines.map(line => JSON.parse(line));
  
  // Aggregate by skill
  const skillCounts = {};
  const designerSkills = {};
  const lastUsed = {};
  
  events.forEach(event => {
    // Total counts
    skillCounts[event.skill] = (skillCounts[event.skill] || 0) + 1;
    
    // Per-designer counts
    if (!designerSkills[event.designer]) {
      designerSkills[event.designer] = {};
    }
    designerSkills[event.designer][event.skill] = 
      (designerSkills[event.designer][event.skill] || 0) + 1;
    
    // Last used
    lastUsed[event.skill] = event.timestamp;
  });
  
  // Sort skills by usage
  const sortedSkills = Object.entries(skillCounts)
    .sort((a, b) => b[1] - a[1]);
  
  // Generate markdown summary
  const summary = `# Skill Usage Summary

**Last updated:** ${new Date().toISOString()}  
**Total events:** ${events.length}

## Most Used Skills

| Skill | Total Uses | Last Used |
|-------|-----------|-----------|
${sortedSkills.map(([skill, count]) => 
  `| \`${skill}\` | ${count} | ${new Date(lastUsed[skill]).toLocaleDateString()} |`
).join('\n')}

## By Designer

${Object.entries(designerSkills).map(([designer, skills]) => {
  const designerTotal = Object.values(skills).reduce((a, b) => a + b, 0);
  const topSkills = Object.entries(skills)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 5)
    .map(([skill, count]) => `\`${skill}\` (${count})`)
    .join(', ');
  
  return `### ${designer}\n- **Total uses:** ${designerTotal}\n- **Top skills:** ${topSkills}`;
}).join('\n\n')}

## Unused Skills

Skills that haven't been used in the last 30 days:

${sortedSkills
  .filter(([skill, _]) => {
    const daysSinceUse = (Date.now() - new Date(lastUsed[skill])) / (1000 * 60 * 60 * 24);
    return daysSinceUse > 30;
  })
  .map(([skill, _]) => `- \`${skill}\` (last used: ${new Date(lastUsed[skill]).toLocaleDateString()})`)
  .join('\n') || '(All skills used recently)'}

---

*Generated by \`.cursor/hooks/skill-usage-tracker.mjs\`*
`;
  
  writeFileSync(USAGE_SUMMARY, summary);
}

readStdin()
  .then((raw) => {
    const skillName = skillFromPayload(raw)
    let data = {}
    try { data = JSON.parse(raw) } catch { /* a bad payload still must not throw */ }
    if (skillName) logUsage(skillName, data)
    console.log(JSON.stringify({}))
  })
  .catch((err) => {
    console.error('Skill usage tracker error:', err.message)
    console.log(JSON.stringify({}))
  })
